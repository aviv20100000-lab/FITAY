async function main() {
  let changed = 0;
  for (const u of UPDATES) {
    const before = await db.execute({
      sql: "SELECT body FROM method_content WHERE id = ?",
      args: [u.id],
    });
    if (!before.rows.length) {
      console.log(`דילוג, לא נמצא: ${u.label}`);
      continue;
    }
    const old = String(before.rows[0].body);
    if (old === u.body) {
      console.log(`ללא שינוי: ${u.label}`);
      continue;
    }
    await db.execute({
      sql: "UPDATE method_content SET body = ? WHERE id = ?",
      args: [u.body, u.id],
    });
    changed += 1;
    console.log(`\n=== ${u.label}\nלפני: ${old}\nאחרי: ${u.body}`);
  }
  console.log(`\nעודכנו ${changed} סעיפים מתוך ${UPDATES.length}.`);
}

main().then(
  () => process.exit(0),
  (err) => {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  }
);
