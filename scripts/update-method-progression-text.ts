async function main() {
  for (const u of UPDATES) {
    const before = await db.execute({
      sql: "SELECT title FROM method_content WHERE id = ?",
      args: [u.id],
    });
    if (!before.rows.length) {
      console.log(`לא נמצא: ${u.title} (${u.id}) — מדלג`);
      continue;
    }
    await db.execute({
      sql: "UPDATE method_content SET title = ?, body = ? WHERE id = ?",
      args: [u.title, u.body, u.id],
    });
    console.log(`עודכן: "${before.rows[0].title}" ← "${u.title}"`);
  }
  console.log("סיום. רענן את לשונית המדריך באפליקציה כדי לראות.");
}

