"use client";

import { useLinkStatus } from "next/link";

/**
 * סימן שהלחיצה נקלטה, על שורת האימון החלופי.
 *
 * הבעיה שזה פותר: לחיצה על השורה טוענת את מסך הבית מחדש מהשרת עם
 * הבחירה בכתובת, וזה לקח כשתי שניות בטלפון. בזמן הזה שום דבר על המסך
 * לא זז. אביב תיאר את זה ב-19 באוגוסט 2026: "נראה סתם תקוע כאילו לא
 * לחצתי". זה הצד החמור יותר של הבעיה, כי מתאמן שחושב שהלחיצה לא נקלטה
 * לוחץ שוב.
 *
 * useLinkStatus מחזיר את מצב הניווט של ה-Link שמעליו, ולכן הרכיב הזה
 * חייב לשבת בתוכו. הוא מוסיף מילה אחת בצד השורה, באותו מקום שבו שורה
 * נעולה מכריזה "נעול", ובאותו גודל וצבע של התוויות האחרות.
 *
 * מילה ולא מסתובב: אין באפליקציה ספינר, ואייקון גנרי אסור כאן. מילה
 * שמופיעה מיד עונה על השאלה היחידה שיש למתאמן באותו רגע.
 */
export default function SwitchingHint() {
  const { pending } = useLinkStatus();
  if (!pending) return null;

  return (
    <span
      className="shrink-0 text-[11px] font-black tracking-[.12em]"
      style={{ color: "var(--wood-1)" }}
    >
      מחליף
    </span>
  );
}
