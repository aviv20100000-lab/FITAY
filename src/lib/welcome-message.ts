export const APP_URL = "https://fitay.vercel.app";

export function welcomeMessage({
  name,
  phone,
  password,
}: {
  name: string;
  phone: string;
  password: string;
}) {
  const first = name.trim().split(/\s+/)[0] || name.trim();

  return [
    `${first}, ברוך הבא ל-FITAY.`,
    "",
    "הכניסה שלך:",
    APP_URL,
    `טלפון: ${phone}`,
    `סיסמה: ${password}`,
    "",
    "כדאי להוסיף את האפליקציה למסך הבית. ככה היא נפתחת מהר,",
    "בלי סרגל הדפדפן, ואפשר לקבל תזכורות.",
    "",
    "באייפון:",
    `1. פתח את ${APP_URL} בספארי`,
    "2. לחץ על סמל השיתוף למטה, ריבוע עם חץ כלפי מעלה",
    "3. בחר הוספה למסך הבית",
    "",
    "באנדרואיד:",
    `1. פתח את ${APP_URL} בכרום`,
    "2. לחץ על שלוש הנקודות למעלה",
    "3. בחר הוספה למסך הבית",
    "",
    "אחרי שהוספת, תפתח את FITAY ממסך הבית ותדליק התראות.",
    "ככה תקבל תזכורת אם עוברים כמה ימים בלי אימון.",
    "",
    "נתראה באימון.",
  ].join("\n");
}
