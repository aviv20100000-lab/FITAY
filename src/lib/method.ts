/** מסביר תבנית קצב ספציפית. מחזיר null לתבניות שאינן 4 תווים (החזקות למשל). */
export function explainTempo(tempo: string): string | null {
  const t = tempo.trim().toUpperCase();
  if (!/^[0-9X]{4}$/.test(t)) return null;
  const word = (c: string) =>
    c === "X" ? "מהר ככל האפשר" : c === "0" ? "בלי עצירה" : `${c} שנ׳`;
  return `ירידה ${word(t[0])} · השהיה ${word(t[1])} · עלייה ${word(t[2])} · השהיה ${word(t[3])}`;
}

