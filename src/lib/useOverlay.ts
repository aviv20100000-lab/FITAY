"use client";

import { useEffect } from "react";

/**
 * מסמן שיש שכבה שמכסה את המסך, כדי שכל סרגל קבוע יסתתר מתחתיה.
 *
 * שתי סיבות, ושתיהן מספיקות לבד.
 *
 * הראשונה היא באג ציור של WebKit. אלמנט עם backdrop-filter מקבל שכבת
 * ציור נפרדת במנוע, וספארי באייפון ממיין את השכבות האלה בלי להסתכל על
 * z-index. סרגל הניווט התחתון מטושטש, ולכן הוא נצבע מעל היומן החודשי
 * וכיסה בדיוק את כפתור השמירה. z-index גבוה יותר לא עזר, כי המיון בכלל
 * לא מסתכל עליו.
 *
 * השנייה היא חור אמיתי בחוויה, שקיים גם במחשב. היומן שואל "לצאת בלי
 * לשמור", אבל סרגל ניווט חי מתחתיו הוא דלת יציאה שעוקפת את השאלה: מתאמן
 * שלוחץ על לשונית באמצע עריכה יוצא בלי המגן הזה. שכבה שמכסה מסך צריכה
 * לחסום ניווט.
 *
 * המונה נדרש כי שכבה יכולה להיפתח מעל שכבה. בלעדיו סגירה של הפנימית
 * הייתה מחזירה את הסרגלים בזמן שהחיצונית עדיין פתוחה.
 */
let openCount = 0;

export function useOverlay(active = true) {
  useEffect(() => {
    if (!active) return;
    openCount += 1;
    document.documentElement.dataset.overlay = "open";
    return () => {
      openCount = Math.max(0, openCount - 1);
      if (openCount === 0) delete document.documentElement.dataset.overlay;
    };
  }, [active]);
}
