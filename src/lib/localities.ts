/**
 * צורה משותפת להשוואת שמות.
 *
 * שמות יישובים נכתבים בכמה צורות: גרשיים, מקף בבאר־שבע, סוגריים אחרי
 * שם שבט, רווח כפול. מתאמן שמקליד "בארשבע" או "פתח תקוה" מתכוון למקום
 * אחד ויחיד, והחיפוש צריך למצוא אותו בלי שילמד את הכתיב שלנו.
 */
export function normalizeName(value: string): string {
  return value
    .replace(/["'`׳״]/g, "")
    .replace(/[-־–]/g, " ")
    .replace(/[()]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * צורה רופפת עוד יותר, לכתיב חופשי.
 *
 * בלי רווחים בכלל, ובלי כפילות של וי"ו ויו"ד. מי שמקליד "בארשבע" מתכוון
 * לבאר שבע, ומי שכותב "פתח תקוה" בווי"ו אחת מתכוון לפתח תקווה. שתי
 * הצורות האלה נפוצות מכדי להיחשב שגיאה, ומתאמן שמחפש את היישוב שלו
 * לא אמור ללמוד את הכתיב של רשות האוכלוסין.
 */
function looseName(value: string): string {
  return normalizeName(value)
    .replace(/s/g, "")
    .replace(/וו/g, "ו")
    .replace(/יי/g, "י")
    .toLocaleLowerCase("he");
}

