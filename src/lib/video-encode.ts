/**
 * התקרה לצלע הארוכה. הצלע הקצרה נגזרת ממנה לפי יחס הצדדים.
 *
 * 1920 ולא 720: איתי מצלם באייפון ב-4K, ומסך אייפון הוא בערך 1170 פיקסלים
 * ברוחב. קליפ לאורך יוצא מכאן 1080x1920, כלומר בדיוק מה שהמסך מסוגל
 * להראות, בלי מתיחה. נמדד ב-18 באוגוסט 2026: ב-720 המסך מתח את הסרטון
 * פי 1.6 והרכות הייתה גלויה לעין.
 */
export const VIDEO_MAX_EDGE = 1920;

/**
 * 22 ולא 26. ההפרש נראה על פרטים דקים: שיער, קצוות קעקוע, וחבל הטבעת.
 * המחיר הוא קובץ גדול פי שלושה בערך, ובכל זאת בערך 3 מגה לעשר שניות,
 * שנטענות בשנייה על סלולרי.
 */
export const VIDEO_CRF = "22";

/**
 * מגביל את שתי הצלעות ל-VIDEO_MAX_EDGE, שומר על יחס הצדדים, ולא מגדיל
 * קליפ שכבר קטן מזה.
 *
 * הקופסה נגזרת מהקלט עצמו ולא ממספר קבוע, ולכן קליפ קטן עובר כמו שהוא.
 * `force_original_aspect_ratio=decrease` מכווץ אל תוך הקופסה בלי לעוות.
 * ה-crop אחריו מוריד פיקסל אחד כשצריך, כי yuv420p לא מקבל צלע אי־זוגית.
 *
 * שתי מגבלות של הבינארי הארוז מכתיבות בדיוק את הצורה הזאת, ושתיהן
 * התגלו בדרך הקשה:
 *
 * 1. `force_divisible_by` נוסף רק ב-ffmpeg 4.4, והבינארי של
 *    @ffmpeg-installer הוא מדצמבר 2018. הוא נופל על
 *    "Option 'force_divisible_by' not found".
 *
 * 2. פסיק בתוך ביטוי מקונן נשבר בבינארי של לינוקס, זה שרץ בוורסל, גם
 *    כשהביטוי עטוף בגרשיים. ניסוח עם `if(gt(iw,ih),...)` עבר בבדיקה
 *    מקומית על הבינארי של ווינדוס ונפל בפרודקשן על
 *    "No such filter: 'ih)'", כלומר המפריד בלע את הפסיקים. הצורה כאן
 *    היא זו שרצה בפרודקשן חודשים בגרסת ה-720: ערך יחיד בגרשיים עם פסיק
 *    אחד, בלי קינון. **אין להחזיר לכאן ביטויים מקוננים.**
 *
 * הפסיק שבין scale ל-crop הוא מפריד רגיל בין שני מסננים, ולכן בטוח.
 *
 * נבדק על הבינארי הארוז דרך spawn, מול 3840x2160, 2160x3840, 2206x2160,
 * 1920x1080, 1080x1920, 1081x1921, 720x1280, 1000x1000, 3836x1954,
 * 1919x1000, 1000x1919, 641x361 ו-464x848, ועל הקובץ שנפל בפרודקשן.
 */
export const VIDEO_SCALE_FILTER =
  `scale='min(${VIDEO_MAX_EDGE},iw)':'min(${VIDEO_MAX_EDGE},ih)'` +
  `:force_original_aspect_ratio=decrease` +
  `,crop=trunc(iw/2)*2:trunc(ih/2)*2`;

