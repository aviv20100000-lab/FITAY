/**
 * התקרה לצלע הארוכה. הצלע הקצרה נגזרת ממנה לפי יחס הצדדים.
 *
 * 1920 ולא 720: איתי מצלם באייפון ב-4K, ומסך אייפון הוא בערך 1170 פיקסלים
 * ברוחב. קליפ לאורך יוצא מכאן 1080x1920, כלומר בדיוק מה שהמסך מסוגל
 * להראות, בלי מתיחה. נמדד ב-18 באוגוסט 2026: ב-720 המסך מתח את הסרטון
 * פי 1.6 והרכות הייתה גלויה לעין.
 */
export const VIDEO_MAX_EDGE = 1920;

/**
 * 22 ולא 26. ההפרש נראה על פרטים דקים: שיער, קצוות קעקוע, וחבל הטבעת.
 * המחיר הוא קובץ גדול פי שלושה בערך, ובכל זאת בערך 3 מגה לעשר שניות,
 * שנטענות בשנייה על סלולרי.
 */
export const VIDEO_CRF = "22";

/**
 * מגביל את שתי הצלעות ל-VIDEO_MAX_EDGE, שומר על יחס הצדדים, ולא מגדיל
 * קליפ שכבר קטן מזה.
 *
 * הענף לפי gt(iw,ih) ולא נוסחה אחת: קליפ לאורך צריך תקרה על הגובה וקליפ
 * לרוחב צריך תקרה על הרוחב. `scale='min(1920,iw)':-2` לבדו היה מוציא
 * קליפ לרוחב ב-1920x1080 אבל קליפ לאורך ב-1920x3413, כלומר מגדיל אותו.
 *
 * ה-trunc מבטיח מספר זוגי, כי yuv420p לא מקבל צלע אי־זוגית. הצלע השנייה
 * מקבלת -2 שכבר מחזיר זוגי בעצמו.
 *
 * במפורש בלי force_divisible_by, שנוסף רק ב-ffmpeg 4.4: הבינארי שנארז
 * ב-@ffmpeg-installer הוא מדצמבר 2018, והוא נופל עליו על
 * "Option 'force_divisible_by' not found". נבדק על הבינארי הארוז עצמו
 * מול 3840x2160, 2160x3840, 1920x1080, 1080x1920, 720x1280, 1000x1000,
 * 3836x1954, 1919x1000 ו-641x361.
 */
export const VIDEO_SCALE_FILTER =
  `scale=w='if(gt(iw,ih),trunc(min(${VIDEO_MAX_EDGE},iw)/2)*2,-2)'` +
  `:h='if(gt(iw,ih),-2,trunc(min(${VIDEO_MAX_EDGE},ih)/2)*2)'`;
